static const struct glyph *lookup(char c)
{
	size_t i;

	c = (char)toupper((unsigned char)c);
	for (i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++)
		if (glyphs[i].c == c)
			return &glyphs[i];
	return lookup('?');
}

int font_text_width(const char *s)
{
	int w = 0;

	for (; *s; s++)
		w += (int)strlen(lookup(*s)->rows[0]) + 1;
	return w > 0 ? w - 1 : 0;
}

void font_draw(uint32_t *fb, int fb_w, int x, int y, const char *s,
               uint32_t color, int clip_x0, int clip_x1)
{
	for (; *s; s++) {
		const struct glyph *g = lookup(*s);
		int gw = (int)strlen(g->rows[0]);
		int r, c;

		if (x >= clip_x1)
			break;
		if (x + gw > clip_x0) {
			for (r = 0; r < FONT_HEIGHT; r++)
				for (c = 0; c < gw; c++) {
					int px = x + c;

					if (g->rows[r][c] == '#' && px >= clip_x0 && px < clip_x1)
						fb[(y + r) * fb_w + px] = color;
				}
		}
		x += gw + 1;
	}
}

void font_normalize(const char *in, char *out, int outlen)
{
	int n = 0, space = 1;
	const unsigned char *p = (const unsigned char *)in;

	for (; *p && n < outlen - 1; p++) {
		unsigned char c = *p;

		if (c >= 0x80) /* drop UTF-8 sequences (accents, emoji, ...) */
			continue;
		if (isspace(c)) {
			if (!space)
				out[n++] = ' ';
			space = 1;
			continue;
		}
		if (!isprint(c))
			continue;
		c = (unsigned char)toupper(c);
		if (lookup((char)c)->c != c)
			c = '?';
		out[n++] = (char)c;
		space = 0;
	}
	while (n > 0 && out[n - 1] == ' ')
		n--;
	out[n] = '\0';
}
